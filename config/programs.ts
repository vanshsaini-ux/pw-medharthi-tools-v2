export function getProgramBySlug(slug: string): ProgramProfile | undefined {
  return PROGRAMS.find((p) => p.slug === slug);
}

/** Buckets the catalogue into three groups for dropdown display - a flat
 * 87-item <select> is unusable, but grouped by level it's a normal-sized,
 * scannable list (browsers render <optgroup> with sticky group headers). */
export function groupProgramsForSelect(programs: ProgramProfile[] = PROGRAMS) {
  const isCertificate = (p: ProgramProfile) => /certificate|certification|qcml/i.test(p.name);
  const certificates = programs.filter(isCertificate);
  const ug = programs.filter((p) => !isCertificate(p) && p.minQualificationLevel === 'class12');
  const pg = programs.filter((p) => !isCertificate(p) && p.minQualificationLevel !== 'class12');

  const toOptions = (list: ProgramProfile[]) =>
    [...list].sort((a, b) => a.name.localeCompare(b.name)).map((p) => ({ value: p.slug, label: p.name }));

  return [
    { label: 'IIT / IIM AI-Driven Certificate Programs', options: toOptions(certificates) },
    { label: 'Postgraduate Programs', options: toOptions(pg) },
    { label: 'Undergraduate Programs', options: toOptions(ug) }
  ].filter((g) => g.options.length > 0);
}

